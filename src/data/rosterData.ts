function classifyArchetype(
  pos: Position,
  skt: number,
  sht: number,
  pas: number,
  chk: number,
  def: number
): PlayerArchetype {
  if (pos === 'G') return 'Brick Wall Goalie';
  if (pos === 'D') {
    if (chk >= def + 3 || chk >= 88) return 'Enforcer';
    return 'Two-Way Defenseman';
  }
  if (chk >= sht + 2 && chk >= pas + 2) return 'Enforcer';
  if (sht >= pas) return 'Sniper';
  return 'Playmaker';
}

function calculateMarketPrice(tier: CardTier, ovr: number): number {
  switch (tier) {
    case 'LEGENDARY':
      return 3200 + (ovr - 94) * 450;
    case 'PLATINUM':
      return 1600 + (ovr - 89) * 220;
    case 'GOLD':
      return 650 + (ovr - 79) * 65;
    case 'SILVER':
      return 240 + (ovr - 69) * 25;
    case 'BRONZE':
    default:
      return 80 + Math.max(0, ovr - 55) * 8;
  }
}

